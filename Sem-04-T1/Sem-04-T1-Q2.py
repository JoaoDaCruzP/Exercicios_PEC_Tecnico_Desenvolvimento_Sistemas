'''Escreva um programa que leia três números inteiros nas variáveis “a”, “b” e “c” e escreva a média deles:'''
print('Vamos calcular a media de três notas? ')
a = int(input('Digite um numero inteiro: '))
b = int(input('Digite outro numero inteiro: '))
c = int(input('Digite mais um numero inteiro: '))

print(f'A média dos valores digitados: {(a+b+c)/3}')