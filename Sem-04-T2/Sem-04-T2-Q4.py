'''Escreva um programa que leia um valor inteiro e mostra na tela no valor booleano True caso o número lido seja maior que 100 ou False caso contrário.

'''
print('Vamos descobrir se o Numero que digitar é maior que "100"')
valor = (int(input('Digite um numero inteiro: ')) > 100)

print(f'Valor digitado é maior que "100"? =  {valor}')