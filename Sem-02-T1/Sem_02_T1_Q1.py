
print('01. Um mago precisa misturar duas substâncias para criar uma poção. Peça ao usuário os dois volumes (em ml) e exiba o total da poção.')

entrada_n1 = float(input('Digite o Primeiro volume: ').strip())
entrada_n2  = float(input('Digite o Segundo volume: ').strip())

#REALIZA A OPERAÇÃO
soma = entrada_n1 + entrada_n2

#MOSTRA O RESULTADO
print(f'\nO resultado da soma dos dois volumes é {soma:.2f}ml')

