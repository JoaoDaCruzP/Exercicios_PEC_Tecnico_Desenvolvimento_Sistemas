print('04. Um dragão come exatamente meia ovelha por dia. Pergunte ao usuário por quantos dias o dragão está solto. Calcule quantas ovelhas ele já comeu nesse tempo!\n')
entrada_dias = float(input('Digite a quantos dias o dragão esta solto: ').strip())

ovelha_inteira = entrada_dias /2    

print(f'O dragão comeu \n{ovelha_inteira} ovelhas')

