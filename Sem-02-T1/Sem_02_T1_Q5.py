
print('05. Crie um programa em que o usuário insira um número inteiro X e você devolva o dobro, triplo e o quadrado de X.')

entrada_valor = input('Digite um valor: ')

dobro = int(entrada_valor) * 2

triplo = int(entrada_valor) * 3

quadrado = int(entrada_valor)**2

print(f'O dobro de {entrada_valor} é {dobro}')
print(f'O triplo de {entrada_valor} é {triplo}')
print(f'O quadro de {entrada_valor} é {quadrado}')
